#!/bin/sh
# Generate the schema code of the bus SDKs from crates/tilr-bus/proto/ (the frozen bus
# schemas; design K4 of openspec/design/unified-bus.md) and check it in:
#
#   scripts/gen-bus-sdk.sh           write sdk/python/src/tilr_bus/proto/ and sdk/deno/gen/
#   scripts/gen-bus-sdk.sh --check   exit 1 naming each file that differs from what the
#                                    schemas generate (CI's `sdk` job)
#
# Python: `*_pb2.py` and `*_pb2.pyi` by protoc (the version scripts/install-tools.sh
# pins: its output differs between versions) in `tilr_bus.proto._gen`, imports
# rewritten into it, and a module per package (`tilr_bus.proto.pane` holds every
# message of tilr.pane.v1). Deno: protoc's descriptor set of the same files, turned
# into static code by tools/gen.ts with protobuf-es (protoc-gen-es, pinned in
# sdk/deno/deno.json and deno.lock) in sdk/deno/gen/pb/, and a module per package
# (sdk/deno/gen/tilr/pane/v1.ts).
# Needs protoc 36.2 and deno on PATH (scripts/install-tools.sh DIR protoc deno).
set -eu
# Sorted by byte: find's list and the globs below.
LC_ALL=C
export LC_ALL

PROTOC_VERSION=36.2

root=$(CDPATH='' cd -- "$(dirname -- "$0")/.." && pwd -P)
proto="$root/crates/tilr-bus/proto"
check=false
case "${1:-}" in
    --check) check=true ;;
    "") ;;
    *) sed -n '5,7p' "$0" >&2; exit 2 ;;
esac

case "$(protoc --version 2>/dev/null)" in
    "libprotoc $PROTOC_VERSION") ;;
    *) echo "gen-bus-sdk: needs protoc $PROTOC_VERSION on PATH (scripts/install-tools.sh DIR protoc), found: $(protoc --version 2>&1 || true)" >&2; exit 1 ;;
esac
command -v deno >/dev/null || { echo "gen-bus-sdk: needs deno on PATH (scripts/install-tools.sh DIR deno)" >&2; exit 1; }

tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

# Python
py="$tmp/python"
mkdir -p "$py/_gen"
(cd "$proto" && find . -name '*.proto' | sed 's|^\./||' | LC_ALL=C sort) > "$tmp/protos"
# shellcheck disable=SC2046 # the file names have no spaces
protoc -I "$proto" --python_out="$py/_gen" --pyi_out="$py/_gen" $(cat "$tmp/protos")
# protoc imports by the schema's path (`import bus_pb2`, `from tilr.pane.v1 import`):
# inside the package they are `tilr_bus.proto._gen...`.
find "$py/_gen" -name '*_pb2.py*' | while read -r file; do
    sed -e 's/^import bus_pb2 as /from tilr_bus.proto._gen import bus_pb2 as /' \
        -e 's/^import bus_pb2$/from tilr_bus.proto._gen import bus_pb2/' \
        -e 's/^from tilr\./from tilr_bus.proto._gen.tilr./' \
        "$file" > "$file.new"
    mv "$file.new" "$file"
done
find "$py/_gen" -type d | while read -r dir; do
    : > "$dir/__init__.py"
done
# One module per package: tilr.bus.v1 is bus.proto and tilr/bus/v1/*.proto.
{
    echo '"""The bus schemas (crates/tilr-bus/proto/), one module per package.'
    echo
    echo 'Generated by scripts/gen-bus-sdk.sh; do not edit.'
    echo '"""'
} > "$py/__init__.py"
for dir in "$py"/_gen/tilr/*/v1; do
    ns=$(basename "$(dirname "$dir")")
    {
        echo "\"\"\"The messages and enums of tilr.$ns.v1."
        echo
        echo 'Generated by scripts/gen-bus-sdk.sh; do not edit.'
        echo '"""'
        echo
        echo '# ruff: noqa: F403'
        [ "$ns" = bus ] && echo 'from tilr_bus.proto._gen.bus_pb2 import *'
        for file in "$dir"/*_pb2.py; do
            file=$(basename "$file" .py)
            echo "from tilr_bus.proto._gen.tilr.$ns.v1.$file import *"
        done
    } > "$py/$ns.py"
done

# Deno
deno_out="$tmp/deno"
# shellcheck disable=SC2046 # the file names have no spaces
protoc -I "$proto" --include_source_info --descriptor_set_out="$tmp/schemas.pb" $(cat "$tmp/protos")
(cd "$root/sdk/deno" && deno run --quiet --frozen --allow-read --allow-write --allow-env tools/gen.ts "$tmp/schemas.pb" "$deno_out")

python_dir="$root/sdk/python/src/tilr_bus/proto"
deno_dir="$root/sdk/deno/gen"
if $check; then
    status=0
    for pair in "$py:$python_dir" "$deno_out:$deno_dir"; do
        new=${pair%%:*}
        old=${pair#*:}
        if ! diff -r -x __pycache__ "$old" "$new" > "$tmp/diff" 2>&1; then
            sed -n 's|^Only in '"$new"'\(.*\): \(.*\)|missing: '"$old"'\1/\2|p; s|^Only in '"$old"'\(.*\): \(.*\)|not generated: '"$old"'\1/\2|p; s|^diff -r -x __pycache__ '"$old"'\([^ ]*\) .*|differs: '"$old"'\1|p' "$tmp/diff" \
                | sed "s|$root/||" >&2
            status=1
        fi
    done
    if [ "$status" -ne 0 ]; then
        echo "gen-bus-sdk: the generated schema code is not what crates/tilr-bus/proto/ generates; run scripts/gen-bus-sdk.sh" >&2
    fi
    exit "$status"
fi
rm -rf "$python_dir" "$deno_dir"
mkdir -p "$(dirname "$python_dir")" "$(dirname "$deno_dir")"
cp -R "$py" "$python_dir"
cp -R "$deno_out" "$deno_dir"
echo "gen-bus-sdk: wrote ${python_dir#"$root"/} and ${deno_dir#"$root"/}"
