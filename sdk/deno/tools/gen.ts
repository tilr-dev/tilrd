// Generates the schema code of the Deno library from the bus schemas
// (`crates/tilr-bus/proto/`, frozen): `gen/schema.ts`, the schema as protobufjs JSON,
// and `gen/tilr/<ns>/v1.ts`, an interface and a codec per message and a constant per
// enum of each package. Run by `scripts/gen-bus-sdk.sh`, not by hand:
//
//   deno run --allow-read --allow-write tools/gen.ts PROTO_DIR OUT_DIR
//
// Field names are protobufjs's camelCase (`pane_id` is `paneId`); 64-bit integers
// are numbers.

import protobuf from "protobufjs";

const HEADER = "// Generated by scripts/gen-bus-sdk.sh from crates/tilr-bus/proto; do not edit.\n";

function protoFiles(dir: string, prefix = ""): string[] {
  const files: string[] = [];
  const entries = [...Deno.readDirSync(`${dir}/${prefix}`)].sort((a, b) =>
    a.name < b.name ? -1 : a.name > b.name ? 1 : 0
  );
  for (const entry of entries) {
    const path = prefix ? `${prefix}/${entry.name}` : entry.name;
    if (entry.isDirectory) files.push(...protoFiles(dir, path));
    else if (entry.name.endsWith(".proto")) files.push(path);
  }
  return files;
}

const SCALARS: Record<string, string> = {
  double: "number",
  float: "number",
  int32: "number",
  uint32: "number",
  sint32: "number",
  fixed32: "number",
  sfixed32: "number",
  int64: "number",
  uint64: "number",
  sint64: "number",
  fixed64: "number",
  sfixed64: "number",
  bool: "boolean",
  string: "string",
  bytes: "Uint8Array",
};

/** The TypeScript name of a field's type, as seen from package `pkg`. */
function typeName(field: protobuf.Field, pkg: string, imports: Set<string>): string {
  const scalar = SCALARS[field.type];
  if (scalar) return scalar;
  const resolved = field.resolvedType;
  if (!resolved) throw new Error(`unresolved type ${field.type} of ${field.fullName}`);
  const owner = resolved.parent!.fullName.replace(/^\./, "");
  if (owner === pkg) return resolved.name;
  const alias = owner.split(".").slice(1, 2).join("");
  imports.add(owner);
  return `${alias}.${resolved.name}`;
}

function comment(text: string | null | undefined, indent: string): string {
  if (!text) return "";
  const lines = text.split("\n").map((line) => line.trimEnd());
  return `${indent}/**\n${
    lines.map((line) => `${indent} *${line ? " " + line : ""}`).join("\n")
  }\n${indent} */\n`;
}

function packageModule(ns: protobuf.Namespace, pkg: string, depth: number): string {
  const imports = new Set<string>();
  const body: string[] = [];
  const nested = ns.nestedArray.slice().sort((a, b) =>
    a.name < b.name ? -1 : a.name > b.name ? 1 : 0
  );
  for (const item of nested) {
    if (item instanceof protobuf.Type) {
      const fields: string[] = [];
      for (const field of item.fieldsArray.slice().sort((a, b) => a.id - b.id)) {
        let type = typeName(field, pkg, imports);
        if (field.map) {
          type = `Record<string, ${type}>`;
        } else if (field.repeated) {
          type = `${type}[]`;
        }
        fields.push(`${comment(field.comment, "  ")}  ${field.name}?: ${type};`);
      }
      for (const oneof of item.oneofsArray) {
        if (oneof.name.startsWith("_")) continue; // proto3 `optional`
        const names = oneof.fieldsArray.map((field) => JSON.stringify(field.name));
        fields.push(
          `  /** Which field of the oneof is set (decoded messages). */\n  ${oneof.name}?: ${
            names.join(" | ")
          };`,
        );
      }
      body.push(
        `${comment(item.comment, "")}export interface ${item.name} {${
          fields.length ? `\n${fields.join("\n")}\n` : ""
        }}\n` +
          `export const ${item.name}: MessageCodec<${item.name}> = codec("${pkg}.${item.name}");\n`,
      );
    } else if (item instanceof protobuf.Enum) {
      const values = Object.entries(item.values)
        .sort((a, b) => a[1] - b[1])
        .map(([name, value]) => `  ${name}: ${value},`);
      body.push(
        `${comment(item.comment, "")}export const ${item.name} = {\n${
          values.join("\n")
        }\n} as const;\n` +
          `export type ${item.name} = typeof ${item.name}[keyof typeof ${item.name}];\n`,
      );
    }
  }
  const up = "../".repeat(depth);
  const lines = [HEADER, `import { codec, type MessageCodec } from "${up}src/schema.ts";`];
  for (const owner of [...imports].sort()) {
    const parts = owner.split(".");
    lines.push(`import type * as ${parts[1]} from "${up}gen/${parts.join("/")}.ts";`);
  }
  return `${lines.join("\n")}\n\n${body.join("\n")}`;
}

function main(): void {
  const [protoDir, outDir] = Deno.args;
  if (!protoDir || !outDir) {
    console.error("usage: gen.ts PROTO_DIR OUT_DIR");
    Deno.exit(2);
  }
  const root = new protobuf.Root();
  root.resolvePath = (_origin, target) => `${protoDir}/${target}`;
  root.loadSync(protoFiles(protoDir), { keepCase: false, alternateCommentMode: true });
  root.resolveAll();

  Deno.mkdirSync(outDir, { recursive: true });
  const json = JSON.stringify(root.toJSON(), null, 2);
  Deno.writeTextFileSync(
    `${outDir}/schema.ts`,
    `${HEADER}// The bus schemas as protobufjs JSON (Root.fromJSON).\nexport const schema = ${json};\n`,
  );
  const tilr = root.lookup("tilr") as protobuf.Namespace;
  for (const ns of tilr.nestedArray as protobuf.Namespace[]) {
    const v1 = ns.lookup("v1") as protobuf.Namespace;
    const pkg = `tilr.${ns.name}.v1`;
    Deno.mkdirSync(`${outDir}/tilr/${ns.name}`, { recursive: true });
    Deno.writeTextFileSync(`${outDir}/tilr/${ns.name}/v1.ts`, packageModule(v1, pkg, 3));
  }
}

main();
