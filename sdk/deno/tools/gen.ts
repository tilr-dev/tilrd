// Generates the schema code of the Deno library from the bus schemas
// (`crates/tilr-bus/proto/`, frozen), with protobuf-es (`@bufbuild/protoc-gen-es`, run
// in this process; versions pinned in deno.json and deno.lock). Run by
// `scripts/gen-bus-sdk.sh`, not by hand:
//
//   deno run --allow-read --allow-write --allow-env tools/gen.ts DESCRIPTOR_SET OUT_DIR
//
// DESCRIPTOR_SET is what `protoc --include_source_info --descriptor_set_out` wrote for
// every schema file. Out come:
//
// - `pb/<file>_pb.ts`: protoc-gen-es's static code, a type and a schema per message
//   and a TypeScript enum per enum (no code is built at run time: no `eval`, no
//   `Function`, so it runs under a strict Content-Security-Policy);
// - `tilr/<ns>/v1.ts`: every message and enum of package `tilr.<ns>.v1`, each message
//   also as a codec (`pane.CreateRequest.encode({...})`, `.decode(bytes)`).
//
// Field names are protobuf-es's camelCase (`pane_id` is `paneId`); 64-bit integers are
// `bigint`; a oneof is `{ case: "name", value }`; enum values drop the enum's prefix
// (`NamedKey.ENTER` for `NAMED_KEY_ENTER`).

import { create, fromBinary } from "@bufbuild/protobuf";
import { CodeGeneratorRequestSchema, FileDescriptorSetSchema } from "@bufbuild/protobuf/wkt";
import { protocGenEs } from "@bufbuild/protoc-gen-es/plugin";

const HEADER = "// Generated by scripts/gen-bus-sdk.sh from crates/tilr-bus/proto; do not edit.\n";

function write(path: string, content: string): void {
  Deno.mkdirSync(path.replace(/\/[^/]+$/, ""), { recursive: true });
  Deno.writeTextFileSync(path, content);
}

/** The package module of `tilr.<ns>.v1`: its files' messages and enums. */
function packageModule(ns: string, files: { path: string; content: string }[]): string {
  const lines = [
    HEADER,
    `// Every message and enum of tilr.${ns}.v1; a message is also a codec.`,
    "",
    'import type { MessageInitShape } from "@bufbuild/protobuf";',
    'import { codec, type MessageCodec } from "../../../src/schema.ts";',
  ];
  const body: string[] = [];
  files.forEach((file, i) => {
    const alias = `pb${i}`;
    lines.push(`import * as ${alias} from "../../${file.path}";`);
    const messages = [...file.content.matchAll(/^export type (\w+) = Message</gm)].map((m) => m[1]);
    const enums = [...file.content.matchAll(/^export enum (\w+) \{/gm)].map((m) => m[1]);
    for (const name of enums.sort()) {
      body.push(`export { ${name}, ${name}Schema } from "../../${file.path}";`);
    }
    for (const name of messages.sort()) {
      body.push(
        `export type ${name} = ${alias}.${name};`,
        `export type ${name}Init = MessageInitShape<typeof ${alias}.${name}Schema>;`,
        `export const ${name}Schema: typeof ${alias}.${name}Schema = ${alias}.${name}Schema;`,
        `export const ${name}: MessageCodec<typeof ${alias}.${name}Schema> = codec(${alias}.${name}Schema);`,
      );
    }
  });
  return `${lines.join("\n")}\n\n${body.join("\n")}\n`;
}

function main(): void {
  const [descriptorSet, outDir] = Deno.args;
  if (!descriptorSet || !outDir) {
    console.error("usage: gen.ts DESCRIPTOR_SET OUT_DIR");
    Deno.exit(2);
  }
  const set = fromBinary(FileDescriptorSetSchema, Deno.readFileSync(descriptorSet));
  const request = create(CodeGeneratorRequestSchema, {
    fileToGenerate: set.file.map((file) => file.name),
    parameter: "target=ts,import_extension=ts",
    protoFile: set.file,
  });
  const response = protocGenEs.run(request);
  if (response.error) throw new Error(`protoc-gen-es: ${response.error}`);
  const byPackage = new Map<string, { path: string; content: string }[]>();
  for (const file of [...response.file].sort((a, b) => (a.name < b.name ? -1 : 1))) {
    const path = `pb/${file.name}`;
    write(`${outDir}/${path}`, file.content);
    const pkg = /\(package tilr\.(\w+)\.v1,/.exec(file.content)?.[1];
    if (!pkg) throw new Error(`${file.name}: no package tilr.<ns>.v1`);
    byPackage.set(pkg, [...(byPackage.get(pkg) ?? []), { path, content: file.content }]);
  }
  for (const [ns, files] of [...byPackage].sort((a, b) => (a[0] < b[0] ? -1 : 1))) {
    write(`${outDir}/tilr/${ns}/v1.ts`, packageModule(ns, files));
  }
}

main();
